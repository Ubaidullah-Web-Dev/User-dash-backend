#!/usr/bin/env bash
# Builds an upload-ready copy of the app for InfinityFree (or any shared host without SSH/Composer).
#
#   deploy/infinityfree/build.sh [--env FILE] [--out DIR] [--no-db]
#
# Output (default var/deploy/infinityfree/):
#   htdocs/        upload the CONTENTS of this folder into the host's htdocs/ folder
#   database.sql   import once with phpMyAdmin (a copy of your local database)
set -euo pipefail

BACKEND="$(cd "$(dirname "$0")/../.." && pwd)"
ENV_FILE="$BACKEND/deploy/infinityfree/prod.env"
OUT="$BACKEND/var/deploy/infinityfree"
DUMP_DB=1
while [ $# -gt 0 ]; do
    case "$1" in
        --env) ENV_FILE="$(realpath "$2")"; shift 2 ;;
        --out) OUT="$(realpath -m "$2")"; shift 2 ;;
        --no-db) DUMP_DB=0; shift ;;
        *) echo "Unknown option: $1" >&2; exit 1 ;;
    esac
done
SITE="$OUT/htdocs"
step() { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }

if [ ! -f "$ENV_FILE" ]; then
    cp "$BACKEND/deploy/infinityfree/prod.env.dist" "$ENV_FILE"
    echo "Created $ENV_FILE - fill in your InfinityFree database details, then run this script again."
    exit 1
fi

# KEY=VALUE lines, taken literally (no shell expansion, so passwords may contain $ ' " etc.)
while IFS= read -r line || [ -n "$line" ]; do
    [[ $line =~ ^[A-Z_]+= ]] || continue
    key=${line%%=*}; value=${line#*=}
    [[ $value =~ ^\"(.*)\"$ || $value =~ ^\'(.*)\'$ ]] && value=${BASH_REMATCH[1]}
    export "$key=$value"
done < "$ENV_FILE"

for var in DB_HOST DB_NAME DB_USER DB_PASSWORD; do
    if [ -z "${!var:-}" ] || [[ ${!var} == *00000000* ]] || [ "${!var}" = change-me ]; then
        echo "Set $var in $ENV_FILE first." >&2; exit 1
    fi
done

# Generate secrets once and store them, so rebuilding keeps logins/JWTs valid.
for var in APP_SECRET JWT_PASSPHRASE; do
    if [ -z "${!var:-}" ]; then
        export "$var=$(php -r 'echo bin2hex(random_bytes(32));')"
        sed -i "s/^$var=.*/$var=${!var}/" "$ENV_FILE"
    fi
done

# Values reused from the local .env (Dotenv parses it exactly like Symfony does).
local_env() { (cd "$BACKEND" && php -r 'require "vendor/autoload.php"; (new Symfony\Component\Dotenv\Dotenv())->bootEnv(".env"); echo $_SERVER[$argv[1]] ?? "";' "$1"); }
[ -n "${MAILER_DSN:-}" ] || export MAILER_DSN="$(local_env MAILER_DSN)"
export CORS_ALLOW_ORIGIN="$(local_env CORS_ALLOW_ORIGIN)"

step "Copying project to $SITE"
rm -rf "$OUT"; mkdir -p "$SITE"
rsync -a "$BACKEND/" "$SITE/" \
    --exclude '/.git' --exclude '/vendor' --exclude '/var' --exclude '/tests' --exclude '/deploy' \
    --exclude '/public/assets' --exclude '/public/bundles' --exclude '/public/pdfs' \
    --exclude '/.env' --exclude '/.env.*' --exclude '/php.ini' --exclude '/phpunit*' --exclude '/.phpunit*' \
    --exclude '/config/jwt/*.pem' --exclude '/*.sql' --exclude '/*.json.bak' --exclude '/login_response.json' \
    --exclude '/check_stock.php' --exclude '/fix_balances.php' --exclude '/insert_companies.php' \
    --exclude '/seed_admins.php' --exclude '/sync_balances.php' --exclude '/sync_balances_all.php' \
    --exclude '/README.md' --exclude '/.gitignore' --exclude '/.editorconfig'
cp "$BACKEND/deploy/infinityfree/htaccess-root" "$SITE/.htaccess"
cd "$SITE"

step "Writing production environment (.env.local.php)"
php -r '
    $e = getenv();
    // "%" must be doubled: DATABASE_URL goes through the container "resolve:" processor.
    $url = sprintf("mysql://%s:%s@%s:%s/%s?serverVersion=%s&charset=utf8mb4",
        rawurlencode($e["DB_USER"]), rawurlencode($e["DB_PASSWORD"]), $e["DB_HOST"], $e["DB_PORT"] ?: "3306",
        rawurlencode($e["DB_NAME"]), rawurlencode($e["DB_SERVER_VERSION"] ?: "mariadb-10.6.0"));
    $vars = [
        "APP_ENV" => "prod",
        "APP_DEBUG" => "0",
        "APP_SECRET" => $e["APP_SECRET"],
        "DATABASE_URL" => str_replace("%", "%%", $url),
        "MESSENGER_TRANSPORT_DSN" => "doctrine://default?auto_setup=0",
        "MAILER_DSN" => $e["MAILER_DSN"] ?: "null://null",
        "JWT_SECRET_KEY" => "%kernel.project_dir%/config/jwt/private.pem",
        "JWT_PUBLIC_KEY" => "%kernel.project_dir%/config/jwt/public.pem",
        "JWT_PASSPHRASE" => $e["JWT_PASSPHRASE"],
        "CORS_ALLOW_ORIGIN" => $e["CORS_ALLOW_ORIGIN"] ?: "*",
    ];
    file_put_contents(".env.local.php", "<?php\n\n// Generated by deploy/infinityfree/build.sh\nreturn " . var_export($vars, true) . ";\n");
'
# Symfony Runtime also expects a .env file to exist next to .env.local.php only when it is missing; keep none.

step "Installing production dependencies (composer install --no-dev)"
composer install --no-dev --optimize-autoloader --no-interaction --no-progress --no-scripts --quiet
# Trim files no request ever loads (the host limits the number of files).
find vendor -mindepth 3 -maxdepth 3 -type d \( -name tests -o -name Tests -o -name docs -o -name doc -o -name .github \) -prune -exec rm -rf {} +
php vendor/symfony/intl/Resources/bin/compress >/dev/null   # gzip the 54MB of locale data (read back via zlib)
find vendor -type f \( -iname '*.md' -o -iname 'phpunit.xml*' -o -iname 'phpstan*.neon*' -o -iname '.gitattributes' -o -iname '.gitignore' -o -iname 'CHANGELOG*' -o -iname 'UPGRADE*' \) -delete

step "Generating JWT keys"
php bin/console lexik:jwt:generate-keypair --overwrite --no-interaction --quiet

step "Building CSS and assets"
mkdir -p var/tailwind
cp -r "$BACKEND/var/tailwind/v"* var/tailwind/ 2>/dev/null || true   # reuse the downloaded Tailwind binary
php bin/console tailwind:build --minify --quiet
php bin/console importmap:install --quiet
php bin/console assets:install public --quiet
php bin/console asset-map:compile --quiet

step "Warming up the production cache"
php bin/console cache:clear --no-warmup --quiet
php bin/console cache:warmup --quiet

step "Cleaning up"
rm -rf var/tailwind var/log bin/phpunit
mkdir -p var/log

VENV="$BACKEND/var/deploy/.venv"   # Python tools for the two steps below
if [ ! -x "$VENV/bin/python" ]; then
    python3 -m venv "$VENV" && "$VENV/bin/pip" install --quiet pypdf pillow
fi

step "Fixing images whose format doesn't match their extension (the host locks those)"
"$VENV/bin/python" "$BACKEND/deploy/infinityfree/fix_images.py" public

step "Shrinking files over the host's 10MB upload limit"
LIMIT=$((10 * 1024 * 1024 - 256 * 1024))
while IFS= read -r -d '' big; do
    if [[ $big != *.pdf ]]; then continue; fi
    before=$(du -h "$big" | cut -f1)
    "$VENV/bin/python" "$BACKEND/deploy/infinityfree/shrink_pdf.py" "$big" "$big.tmp" 2>/dev/null && mv "$big.tmp" "$big"
    echo "  ${big#./}: $before -> $(du -h "$big" | cut -f1)"
done < <(find . -type f -size +"${LIMIT}c" -print0)
TOO_BIG=$(find . -type f -size +"${LIMIT}c")
if [ -n "$TOO_BIG" ]; then
    echo "These files are still over the 10MB upload limit:" >&2; echo "$TOO_BIG" >&2; exit 1
fi
FILES=$(find . -type f | wc -l)
SIZE=$(du -sh . | cut -f1)

if [ "$DUMP_DB" = 1 ]; then
    step "Exporting local database to $OUT/database.sql"
    DSN="$(local_env DATABASE_URL)"
    eval "$(php -r '
        $p = parse_url($argv[1]);
        foreach (["DUMP_HOST" => $p["host"] ?? "127.0.0.1", "DUMP_PORT" => $p["port"] ?? 3306,
                  "DUMP_USER" => urldecode($p["user"] ?? ""), "DUMP_PASS" => urldecode($p["pass"] ?? ""),
                  "DUMP_NAME" => ltrim($p["path"] ?? "", "/")] as $k => $v) echo $k, "=", escapeshellarg((string) $v), "\n";
    ' "$DSN")"
    DUMP_BIN=$(command -v mariadb-dump || command -v mysqldump)
    MYSQL_PWD="$DUMP_PASS" "$DUMP_BIN" -h "$DUMP_HOST" -P "$DUMP_PORT" -u "$DUMP_USER" \
        --single-transaction --skip-lock-tables --skip-add-locks --no-tablespaces --skip-triggers \
        --default-character-set=utf8mb4 "$DUMP_NAME" \
    | sed -E \
        -e '/^\/\*M?!999999\\- enable the sandbox mode \*\//d' \
        -e 's/utf8mb4_uca1400_[a-z0-9_]+/utf8mb4_unicode_ci/g' \
        -e 's/ DEFINER=`[^`]*`@`[^`]*`//g' \
    > "$OUT/database.sql"
    # MariaDB 11+/12 collations are unknown to the host's older server; the sed above maps them to utf8mb4_unicode_ci.
fi

step "Done"
echo "  Site:     $SITE  ($FILES files, $SIZE)"
[ "$DUMP_DB" = 1 ] && echo "  Database: $OUT/database.sql ($(du -h "$OUT/database.sql" | cut -f1))"
echo "  Next: import database.sql in phpMyAdmin, then upload the contents of htdocs/ (see deploy/infinityfree/README.md)."
